package ee.jakarta.tck.faces.faces50.view_scope;

import java.io.IOException;

import jakarta.inject.Inject;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;

/**
 * Invalidates the current session, if any, and then writes the amount of created and destroyed {@link Issue6087Bean} instances as {@code created,destroyed}.
 */
@WebServlet("/issue6087-session")
public class Issue6087SessionServlet extends HttpServlet {

    private static final long serialVersionUID = 1L;

    @Inject
    private Issue6087Counter counter;

    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response) throws IOException {
        HttpSession session = request.getSession(false);

        if (session != null) {
            session.invalidate();
        }

        response.getWriter().write(counter.getCreated() + "," + counter.getDestroyed());
    }

}
